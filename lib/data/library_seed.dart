/// A seeded clause: title, body (lines starting `- ` are sub-items).
typedef SeedClause = ({
  String title,
  String body,
  bool optional,
  bool enabledByDefault,
});

typedef SeedTemplate = ({
  String name,
  String kind,
  String preamble,
  String closing,
  Map<String, String> defaults,
  List<SeedClause> clauses,
});

SeedClause _c(String title, String body) =>
    (title: title, body: body, optional: false, enabledByDefault: true);

SeedClause _opt(String title, String body) =>
    (title: title, body: body, optional: true, enabledByDefault: false);

